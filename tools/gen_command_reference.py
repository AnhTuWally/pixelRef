"""Regenerate docs/commands.md from the running command registry.

    python tools/gen_command_reference.py

Starts pixelRef offscreen with every built-in plugin, then lists each command
with its signature, its first docstring line, its alias and whether it is
undoable. Run it after adding or changing commands.
"""

from __future__ import annotations

import inspect
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from PySide6.QtCore import QSettings, QStandardPaths  # noqa: E402

QStandardPaths.setTestModeEnabled(True)
QSettings.setDefaultFormat(QSettings.IniFormat)


def signature(fn) -> str:  # noqa: ANN001
    try:
        text = str(inspect.signature(fn))
    except (TypeError, ValueError):
        return "(...)"
    return text.split(" -> ")[0].replace("'", "")


def main() -> int:
    from pixelref.ui import create_app

    app = create_app([], persist_layout=False, load_user_files=False)
    registry = app.session.commands
    groups: dict[str, list] = {}
    seen: set[str] = set()
    for name in registry.names():
        command = registry.resolve(name)
        if command.name in seen:
            continue
        seen.add(command.name)
        top = command.name.split(".")[0]
        plugin = command.plugin or ("kernel (UI)" if top in ("tools", "ui", "keymap", "wm", "escape",
                                                             "command_search") else "kernel")
        groups.setdefault(plugin, []).append(command)
    lines = [
        "# Command reference",
        "",
        "Generated by `python tools/gen_command_reference.py` — do not edit by hand.",
        "",
        "Every command is callable as `pxcmd.<name>(...)` (and as `pxcmd.<alias>(...)` when it has one).",
        "Undoable commands are one undo step each (nested commands join the outer step).",
        "Commands of the `kernel (UI)` group and of plugins' UI halves need the desktop app;",
        "the rest also work headless (batch mode, scripts).",
        "",
    ]
    order = ["kernel", "kernel (UI)"] + sorted(g for g in groups if g not in ("kernel", "kernel (UI)"))
    for group in order:
        commands = groups.get(group)
        if not commands:
            continue
        lines += [f"## {group}", "", "| Command | Alias | Undo | Description |", "| --- | --- | --- | --- |"]
        for command in sorted(commands, key=lambda c: c.name):
            doc = (command.doc or inspect.getdoc(command.fn) or "").strip().splitlines()
            summary = doc[0] if doc else ""
            call = f"`{command.name}{signature(command.fn)}`".replace("|", "\\|")
            alias = f"`{command.alias}`" if command.alias else ""
            lines.append(f"| {call} | {alias} | {'yes' if command.undoable else ''} | {summary.replace('|', '/')} |")
        lines.append("")
    out = ROOT / "docs" / "commands.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out} ({sum(len(c) for c in groups.values())} commands)")
    app.close(force=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
